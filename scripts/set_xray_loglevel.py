#!/usr/bin/env python3
"""Set Xray loglevel in the 3x-ui source of truth (settings.xrayTemplateConfig).

Why: the running Xray config (/usr/local/x-ui/bin/config.json) is GENERATED by
the 3x-ui panel from the `xrayTemplateConfig` row of its SQLite database.
Patching the generated file is pointless (regeneration reverts it). This script
changes the template itself, so `warning` survives restarts/redeploys/regeneration.

Scope: touches ONLY settings.xrayTemplateConfig.log.loglevel. Access log stays
enabled (netlink-ip-monitor parses it). No inbounds/clients/keys are read or
modified.

Modes:
  default        dry-run: print current loglevel and what would change
  --apply        perform the change (with a timestamped backup of the old value)

Exit codes: 0 ok/no-op, 1 error, 2 would-change (dry-run only)
"""
import argparse
import json
import os
import shutil
import sqlite3
import sys
import tempfile
import time
from pathlib import Path

DEFAULT_DB = "/etc/x-ui/x-ui.db"
TEMPLATE_KEY = "xrayTemplateConfig"
ALLOWED_LEVELS = {"debug", "info", "warning", "error", "none"}


def eprint(msg: str) -> None:
    print(msg, file=sys.stderr)


def load_template(db_path: str) -> str:
    conn = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True, timeout=10)
    try:
        row = conn.execute(
            "SELECT value FROM settings WHERE key = ?", (TEMPLATE_KEY,)
        ).fetchone()
    finally:
        conn.close()
    if row is None:
        raise RuntimeError(f"key {TEMPLATE_KEY!r} not found in settings")
    return row[0]


def save_template(db_path: str, new_value: str) -> None:
    conn = sqlite3.connect(db_path, timeout=10)
    try:
        cur = conn.execute(
            "UPDATE settings SET value = ? WHERE key = ?",
            (new_value, TEMPLATE_KEY),
        )
        if cur.rowcount != 1:
            conn.rollback()
            raise RuntimeError("update touched unexpected number of rows")
        conn.commit()
    finally:
        conn.close()


def safe_log_section(parsed: dict) -> str:
    log = parsed.get("log")
    if not isinstance(log, dict):
        return "<missing>"
    # Only paths/level are non-sensitive; never dump the whole template.
    return json.dumps(
        {k: log.get(k) for k in ("access", "error", "loglevel") if k in log}
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=DEFAULT_DB)
    ap.add_argument("--loglevel", default="warning", choices=sorted(ALLOWED_LEVELS))
    ap.add_argument("--apply", action="store_true",
                    help="actually write (default: dry-run)")
    ap.add_argument("--backup-dir", default="/root/netlink-stabilize-backups",
                    help="where to store the pre-change template backup")
    args = ap.parse_args()

    raw = load_template(args.db)
    try:
        parsed = json.loads(raw)
        if not isinstance(parsed, dict):
            raise ValueError("template root is not an object")
    except ValueError as exc:
        eprint(f"ERROR: {TEMPLATE_KEY} is not valid JSON: {exc}")
        return 1

    log = parsed.get("log")
    current = log.get("loglevel") if isinstance(log, dict) else None
    print(f"db                 : {args.db}")
    print(f"key                : {TEMPLATE_KEY}")
    print(f"mode               : {'apply' if args.apply else 'dry-run (no changes)'}")
    print(f"log section (safe) : {safe_log_section(parsed)}")

    if current == args.loglevel:
        print(f"RESULT: no-op, loglevel already '{args.loglevel}'")
        return 0

    if args.loglevel not in ALLOWED_LEVELS:
        eprint(f"ERROR: loglevel '{args.loglevel}' not allowed")
        return 1

    if not args.apply:
        print(f"RESULT: would change loglevel '{current}' -> '{args.loglevel}' (dry-run)")
        return 2

    # Build the new template: mutate only log.loglevel, preserve everything else.
    if not isinstance(parsed.get("log"), dict):
        parsed["log"] = {}
    parsed["log"]["loglevel"] = args.loglevel
    new_raw = json.dumps(parsed, ensure_ascii=False)

    # Timestamped backup of the old raw value (root-only).
    ts = time.strftime("%Y%m%d-%H%M%S")
    bdir = Path(args.backup_dir)
    bdir.mkdir(parents=True, exist_ok=True)
    os.chmod(bdir, 0o700)
    bfile = bdir / f"xrayTemplateConfig.{ts}.json"
    bfile.write_text(raw, encoding="utf-8")
    os.chmod(bfile, 0o600)

    # Atomic-ish write: update inside a transaction, verify after.
    save_template(args.db, new_raw)
    check = load_template(args.db)
    if json.loads(check).get("log", {}).get("loglevel") != args.loglevel:
        eprint("ERROR: verification read-back mismatch, restoring backup value")
        save_template(args.db, raw)
        return 1

    print(f"backup             : {bfile}")
    print(f"RESULT: loglevel '{current}' -> '{args.loglevel}' applied and verified")
    print("NOTE: panel must be restarted (systemctl restart x-ui) to regenerate"
          " bin/config.json; restart is performed by the stabilize workflow,"
          " not by this script.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
